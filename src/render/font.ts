const GW = 5, GH = 7;
const GLYPHS: Record<string, Uint8Array> = {};
for (const [k, rows] of Object.entries(ROWS)) {
  const bits = new Uint8Array(GW * GH);
  rows.join('').split('').forEach((ch, i) => (bits[i] = ch === '#' ? 1 : 0));
  GLYPHS[k] = bits;
}

export const FONT_W = GW + 1; // glyph + 1 px spacing
export const FONT_H = GH + 1;

export function textWidth(s: string, scale = 1): number { return (s.length * FONT_W - 1) * scale; }

export function drawText(fb: FrameBuffer, s: string, x: number, y: number, c: number, shadow = -1, scale = 1): void {
  s = s.toUpperCase();
  for (let n = 0; n < s.length; n++) {
    const g = GLYPHS[s[n]] ?? GLYPHS['?'];
    const ox = x + n * FONT_W * scale;
    for (let i = 0; i < GW * GH; i++) if (g[i]) {
      const px = ox + (i % GW) * scale, py = y + ((i / GW) | 0) * scale;
      if (shadow >= 0) fb.rect(px + scale, py + scale, scale, scale, shadow);
    }
    for (let i = 0; i < GW * GH; i++) if (g[i]) {
      fb.rect(ox + (i % GW) * scale, y + ((i / GW) | 0) * scale, scale, scale, c);
    }
  }
}

export function drawTextCentered(fb: FrameBuffer, s: string, cx: number, y: number, c: number, shadow = -1, scale = 1): void {
  drawText(fb, s, Math.round(cx - textWidth(s, scale) / 2), y, c, shadow, scale);
}
